"""
«Сегодня» по Ташкенту.

Бот живёт на VPS в UTC, фермер — в Asia/Tashkent (UTC+5). Пуш
планируется по Ташкенту, ряд Open-Meteo запрашивается по Ташкенту, но
все расчёты «сегодня» шли через date.today() по зоне сервера: с 00:00 до
04:59 по Ташкенту это ещё вчера. Виноградник поливается самотёком
сутками, и фермер в 00:30 жмёт «✅ Suv berdim» -> «Kecha» — якорь
водного баланса вставал на день раньше реального; /suv в 04:30 печатал
день недели и дату на день раньше погодного дня, под который движок
выбрал полив. Аудит 18.08.2026, bot/main.py:654.

Одна функция на весь проект, чтобы «сегодня» не расходилось между
ботом, кабинетом и скриптами.
"""

from __future__ import annotations

from datetime import date, datetime
from zoneinfo import ZoneInfo

TZ = ZoneInfo("Asia/Tashkent")


def now() -> datetime:
    """Текущее время по Ташкенту, со временной зоной."""
    return datetime.now(TZ)


def today() -> date:
    """Сегодняшняя дата по Ташкенту — единственное «сегодня» в проекте."""
    return now().date()
