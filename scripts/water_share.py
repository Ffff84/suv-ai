def compute(wedges):
    rows = []
    for wedge, total_tha, items in wedges:
        for (name, key, proxy, tha, note) in items:
            crop = CROPS[proxy] if proxy != "paddy" else PADDY
            extra = RICE_FLOOD_MM if proxy == "paddy" else 0.0
            m3 = net_m3_per_ha(crop, extra)
            rows.append({
                "wedge": wedge, "name": name, "key": key, "tha": tha,
                "m3_per_ha": m3, "km3": tha * 1000 * m3 / 1e9, "note": note,
            })
    return rows


def report(rows):
    area_all = sum(r["tha"] for r in rows)
    water_all = sum(r["km3"] for r in rows)
    area_cov = sum(r["tha"] for r in rows if r["key"])
    water_cov = sum(r["km3"] for r in rows if r["key"])

    print("  SUV AI — гектары и кубометры, замер"
          f" {date.today().isoformat()}")
    print("  " + "-" * 66)
    wedge = None
    for r in rows:
        if r["wedge"] != wedge:
            wedge = r["wedge"]
            print(f"\n  {wedge}")
        mark = "  " if r["key"] else "??" if "неатриб" in r["name"] else "--"
        print(f"   {mark} {r['name']:<34} {r['tha']:7.1f} тыс.га"
              f"  {r['m3_per_ha']:7.0f} м³/га  {r['km3']:6.2f} км³")
    print("\n  " + "-" * 66)
    print(f"  Всего:    {area_all:8.1f} тыс. га   {water_all:6.1f} км³ нетто"
          f"  (~{water_all / 0.55:.0f} км³ брутто при КПД 0,55)")
    print(f"  Покрыто:  {area_cov:8.1f} тыс. га   {water_cov:6.1f} км³")
    print(f"  ДОЛЯ:     {100 * area_cov / area_all:5.1f}% площади"
          f"      {100 * water_cov / water_all:5.1f}% воды")
    print("\n  Замер 09.09 (шестёрка): 64,8% площади, 59,5% воды.")
    print("  «--» — движок не считает; «??» — неатрибутированный остаток.")


def selftest():
    """Формула обязана воспроизводить пять чисел замера 09.09."""
    published = {"cotton": 9055, "winter_wheat": 3861, "tomato": 8031,
                 "apple": 9304, "grape": 7368}
    for key, pub in published.items():
        got = net_m3_per_ha(CROPS[key])
        assert abs(got - pub) / pub < 0.005, (key, pub, got)


