# Сев/распускание для расчёта: типичные даты записей движка.
_YEAR = 2026


def _start(crop: Crop) -> date:
    m, d = crop.typical_sowing
    # Озимые стартуют прошлой осенью, чтобы сезон был непрерывным.
    year = _YEAR - 1 if m >= 9 else _YEAR
    return date(year, m, d)


def net_m3_per_ha(crop: Crop, extra_mm: float = 0.0) -> float:
    """Нетто-потребность сезона, м³/га — формула замера 09.09."""
    total = 0.0
    for i, day in enumerate(season(ST, _start(crop), sum(crop.stages))):
        e0, _ = et0(day, ST.lat, ST.elevation_m)
        total += max(0.0, stage_and_kc(crop, i).kc * e0
                     - EFF_RAIN * day.rainfall)
    return (total + extra_mm) * 10.0


